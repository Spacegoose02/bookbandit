/** `base` is the device's api_endpoint: https://host/kobo/<token>. */
export function koboResources(base: string): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(NATIVE)) {
    out[k] = typeof v === "string" && v.startsWith(STORE_API) ? base + v.slice(STORE_API.length) : v;
  }
  out.image_host = base;
  out.image_url_template = `${base}/covers/{ImageId}/{Width}/{Height}/false/image.jpg`;
  out.image_url_quality_template = `${base}/covers/{ImageId}/{Width}/{Height}/{Quality}/{IsGreyscale}/image.jpg`;
  return out;
}
